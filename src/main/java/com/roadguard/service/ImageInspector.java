package com.roadguard.service;

import com.roadguard.exception.ValidationException;

import javax.imageio.ImageIO;
import javax.imageio.ImageReader;
import javax.imageio.stream.ImageInputStream;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Iterator;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Decides whether an uploaded file really is a photo we accept. The file name and the Content-Type header
 * are client-supplied and therefore only cross-checked; the decision is made from the file's bytes:
 * <ol><li>size limit</li><li>magic number (JPEG / PNG / WebP)</li><li>the declared type and extension must agree
 * with the detected type</li><li>image dimensions are read from the file header and limited (decompression-bomb guard)</li></ol>
 * The stored name is always generated by the server, so a hostile file name can never reach the file system.
 */
public final class ImageInspector {
    public record ImageInfo(String contentType, String extension, int width, int height) {}

    private static final Set<String> ALLOWED_EXTENSIONS = Set.of("jpg", "jpeg", "png", "webp");
    private static final Map<String, String> CANONICAL_TYPE = Map.of("image/jpg", "image/jpeg", "image/pjpeg", "image/jpeg");

    private ImageInspector() {}

    public static ImageInfo inspect(byte[] data, String declaredName, String declaredContentType, long maxBytes, long maxPixels) {
        if (data == null || data.length == 0) throw fail("The photo is empty.");
        if (data.length > maxBytes) throw fail("The photo is too large. The limit is " + (maxBytes / (1024 * 1024)) + " MB.");

        String detected = sniff(data);
        if (detected == null) throw fail("Only JPEG, PNG or WebP photos are allowed. This file is not a supported image.");

        if (declaredContentType != null && !declaredContentType.isBlank() && !declaredContentType.equalsIgnoreCase("application/octet-stream")) {
            String type = declaredContentType.split(";")[0].trim().toLowerCase(Locale.ROOT);
            type = CANONICAL_TYPE.getOrDefault(type, type);
            if (!type.equals(detected)) throw fail("The file's content does not match its declared type (" + type + ").");
        }
        if (declaredName != null && !declaredName.isBlank()) checkFileName(declaredName, detected);

        int[] size = switch (detected) {
            case "image/jpeg", "image/png" -> readDimensionsWithImageIo(data);
            default -> readWebpDimensions(data);
        };
        if (size[0] <= 0 || size[1] <= 0) throw fail("The photo could not be read. It may be corrupted.");
        if ((long) size[0] * size[1] > maxPixels) throw fail("The photo has too many pixels. Please use a smaller image.");

        String ext = switch (detected) {
            case "image/jpeg" -> "jpg";
            case "image/png" -> "png";
            default -> "webp";
        };
        return new ImageInfo(detected, ext, size[0], size[1]);
    }

    /** Detects the real type from the first bytes. Returns null when it is not JPEG/PNG/WebP. */
    static String sniff(byte[] d) {
        if (d.length >= 3 && (d[0] & 0xFF) == 0xFF && (d[1] & 0xFF) == 0xD8 && (d[2] & 0xFF) == 0xFF) return "image/jpeg";
        if (d.length >= 8 && (d[0] & 0xFF) == 0x89 && d[1] == 'P' && d[2] == 'N' && d[3] == 'G'
                && d[4] == 0x0D && d[5] == 0x0A && d[6] == 0x1A && d[7] == 0x0A) return "image/png";
        if (d.length >= 16 && ascii(d, 0, 4).equals("RIFF") && ascii(d, 8, 4).equals("WEBP")) {
            String chunk = ascii(d, 12, 4);
            if (chunk.equals("VP8 ") || chunk.equals("VP8L") || chunk.equals("VP8X")) return "image/webp";
        }
        return null;
    }

    static void checkFileName(String name, String detectedType) {
        if (name.length() > 255) throw fail("The file name is too long.");
        if (name.contains("/") || name.contains("\\") || name.contains("..") || name.chars().anyMatch(Character::isISOControl)) {
            throw fail("The file name contains characters that are not allowed.");
        }
        int dot = name.lastIndexOf('.');
        String ext = dot < 0 ? "" : name.substring(dot + 1).toLowerCase(Locale.ROOT);
        if (!ALLOWED_EXTENSIONS.contains(ext)) throw fail("The file name must end in .jpg, .jpeg, .png or .webp.");
        String fromExt = ext.equals("png") ? "image/png" : ext.equals("webp") ? "image/webp" : "image/jpeg";
        if (!fromExt.equals(detectedType)) throw fail("The file extension does not match the file's real content.");
    }

    private static int[] readDimensionsWithImageIo(byte[] data) {
        try (ImageInputStream in = ImageIO.createImageInputStream(new ByteArrayInputStream(data))) {
            Iterator<ImageReader> readers = ImageIO.getImageReaders(in);
            if (!readers.hasNext()) throw fail("The photo could not be read. It may be corrupted.");
            ImageReader reader = readers.next();
            try {
                reader.setInput(in, true, true);
                return new int[]{reader.getWidth(0), reader.getHeight(0)};
            } finally {
                reader.dispose();
            }
        } catch (IOException | RuntimeException e) {
            if (e instanceof ValidationException ve) throw ve;
            throw fail("The photo could not be read. It may be corrupted.");
        }
    }

    private static int[] readWebpDimensions(byte[] d) {
        String chunk = ascii(d, 12, 4);
        try {
            switch (chunk) {
                case "VP8X" -> {   // extended: 24-bit width-1 at 24, height-1 at 27
                    return new int[]{1 + le24(d, 24), 1 + le24(d, 27)};
                }
                case "VP8L" -> {   // lossless: signature 0x2F, then 14+14 bits
                    if ((d[20] & 0xFF) != 0x2F) return new int[]{0, 0};
                    long bits = (d[21] & 0xFFL) | ((d[22] & 0xFFL) << 8) | ((d[23] & 0xFFL) << 16) | ((d[24] & 0xFFL) << 24);
                    return new int[]{(int) (bits & 0x3FFF) + 1, (int) ((bits >> 14) & 0x3FFF) + 1};
                }
                default -> {       // lossy: start code 9D 01 2A at 23, then 14-bit width and height
                    if ((d[23] & 0xFF) != 0x9D || d[24] != 0x01 || (d[25] & 0xFF) != 0x2A) return new int[]{0, 0};
                    return new int[]{((d[26] & 0xFF) | ((d[27] & 0xFF) << 8)) & 0x3FFF, ((d[28] & 0xFF) | ((d[29] & 0xFF) << 8)) & 0x3FFF};
                }
            }
        } catch (ArrayIndexOutOfBoundsException e) {
            return new int[]{0, 0};
        }
    }

    private static int le24(byte[] d, int i) {
        return (d[i] & 0xFF) | ((d[i + 1] & 0xFF) << 8) | ((d[i + 2] & 0xFF) << 16);
    }

    private static String ascii(byte[] d, int from, int len) {
        return new String(d, from, len, StandardCharsets.ISO_8859_1);
    }

    private static ValidationException fail(String message) {
        return new ValidationException(Map.of("image", message));
    }
}
